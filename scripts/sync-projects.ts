import fs from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'
import { extractSections, plainText, publicEditorial, redactLocalPaths, generatedProjectIds } from '../src/lib/project-source'
import type { Project, ProjectArtifacts } from '../src/types'

const root = process.cwd()
const projectRoot = path.join(root, 'Projects')
const publicRoot = path.join(root, 'public')
const target = path.join(root, 'src/data/projects.ts')
const validateOnly = process.argv.includes('--validate-only')

export function syncProjects() {
  const projects: Project[] = []
  const errors: string[] = []
  const copies: Array<[string, string]> = []
  const ids = new Set<string>()
  for (const folder of fs.readdirSync(projectRoot, { withFileTypes: true }).filter(f => f.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const source = path.join(projectRoot, folder.name)
    const readme = path.join(source, 'README.md')
    if (!fs.existsSync(readme)) continue
    const { data: fm, content } = matter(fs.readFileSync(readme, 'utf8'))
    if (!fm.id || ids.has(fm.id)) { errors.push(`Missing or duplicate project ID: ${folder.name}`); continue }
    ids.add(fm.id)
    if (!fm.portfolio?.summary?.en) { errors.push(`Missing editorial summary: ${fm.id}`); continue }
    const portfolio = publicEditorial(fm.portfolio)
    const sections = extractSections(content)
    const artifacts: ProjectArtifacts = { extraUrls: [] }
    const publishFile = (filename: string | undefined, label: string) => {
      if (!filename) return undefined
      const file = path.resolve(source, filename)
      if (!file.startsWith(source + path.sep) || !fs.existsSync(file)) { errors.push(`Missing or unsafe artifact: ${fm.id}/${filename}`); return undefined }
      const destination = path.join(publicRoot, 'artifacts', fm.id, filename)
      copies.push([file, destination])
      const url = `/artifacts/${fm.id}/${filename.split(/[\\/]/).map(encodeURIComponent).join('/')}`
      artifacts.extraUrls!.push({ label, url })
      return url
    }
    const art = fm.artifacts ?? {}
    artifacts.paperUrl = publishFile(art.paper, 'Research report')
    artifacts.rReportUrl = publishFile(art.r_report, 'Analysis report')
    artifacts.posterUrl = publishFile(art.poster, 'Poster')
    artifacts.slidesUrl = publishFile(art.slides, 'Presentation')
    for (const [i, name] of (art.notebooks ?? []).entries()) {
      const url = publishFile(name, `Notebook ${i + 1}`)
      if (i === 0) artifacts.notebookUrl = url
    }
    for (const [i, name] of (art.datasets ?? []).entries()) {
      const url = publishFile(name, `Dataset ${i + 1}`)
      if (i === 0) artifacts.datasetUrl = url
    }
    for (const extra of art.extra ?? []) publishFile(extra.file, extra.label)
    const cover = publishFile(art.cover_image, 'Project image')
    artifacts.extraUrls = artifacts.extraUrls!.filter(item => item.label !== 'Project image')
    const image = portfolio.image ?? cover ?? fm.image
    if (portfolio.image && !fs.existsSync(path.join(publicRoot, portfolio.image))) errors.push(`Missing editorial image: ${portfolio.image}`)
    const record: Project = {
      id: fm.id, title: plainText(fm.title), category: fm.category, period: fm.period,
      summary: portfolio.summary.en, summaryId: portfolio.summary.id,
      problem: portfolio.problem?.en ?? sections.problem ?? '',
      methodology: portfolio.methodology?.en ?? sections.methodology ?? '',
      results: portfolio.results?.en ?? sections.results ?? '',
      tags: fm.tags ?? [], portfolio, artifacts,
      ...(image ? { image } : {}),
      ...(fm.award ? { award: plainText(fm.award).replace(/[^\p{L}\p{N}\s&.,:()/-]/gu, '').trim() } : {}),
      ...(fm.githubUrl ? { githubUrl: fm.githubUrl } : {}),
      ...(fm.demoUrl ? { demoUrl: fm.demoUrl } : {}),
      ...(fm.paperUrl ? { paperUrl: fm.paperUrl } : {}),
      ...(sections.dataScope ? { dataScope: sections.dataScope } : {})
    }
    for (const url of [record.githubUrl, record.demoUrl, record.paperUrl]) if (url && !/^https:\/\//.test(url)) errors.push(`Unsafe URL: ${fm.id}`)
    projects.push(record)
  }
  const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  for (const id of previous ? generatedProjectIds(previous) : []) {
    if (!ids.has(id)) errors.push(`Sync would remove existing project: ${id}`)
  }
  if (errors.length) throw new Error(errors.join('\n'))
  if (!validateOnly) {
    for (const [source, destination] of copies) {
      fs.mkdirSync(path.dirname(destination), { recursive: true })
      if (/\.(html?|ipynb|rmd|md|r|py)$/i.test(source)) fs.writeFileSync(destination, redactLocalPaths(fs.readFileSync(source, 'utf8')))
      else fs.copyFileSync(source, destination)
    }
    fs.writeFileSync(target, `// Generated by projects:sync. Edit project README frontmatter instead.\nimport { Project } from '../types'\n\nexport const PROJECTS_DATA: Project[] = ${JSON.stringify(projects, null, 2)}\n`)
  }
  console.log(`${validateOnly ? 'Validated' : 'Synced'} ${projects.length} projects and ${copies.length} artifact references.`)
}
syncProjects()
